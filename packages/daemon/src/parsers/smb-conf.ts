/** A parsed section span over the original `lines` array. */
export interface SectionSpan {
  /**
   * The service name as Samba holds it: the text between `[` and the FIRST
   * `]`, whitespace runs collapsed, NOT trimmed (`[ public]` is " public", a
   * share of its own). Null for the preamble before the first header, or a
   * header Samba cannot load (no `]`, or a blank name).
   */
  name: string | null
  /**
   * The service identity ({@link smbSectionKey}): sections with one key are
   * one service (Samba merges them). Null for the preamble and for an
   * unloadable header.
   */
  key: string | null
  /** Index of the `[name]` header line, or null for the preamble. */
  headerIndex: number | null
  /** First line index of the section (the header line, or 0 for the preamble). */
  start: number
  /**
   * First line after the header — a header continued with a trailing
   * backslash swallows the next line whole (testparm 4.25).
   */
  bodyStart: number
  /** One past the last line index of the section (exclusive). */
  end: number
}

/** The whole file as its original lines plus the section overlay. */
export interface SmbConfDoc {
  lines: string[]
  sections: SectionSpan[]
}

/** Strip a single trailing CR so CRLF files interpret cleanly (kept on write). */
function content(line: string): string {
  return line.endsWith('\r') ? line.slice(0, -1) : line
}

/** Does the trimmed line begin a comment (`#` or `;`)? */
function isComment(trimmed: string): boolean {
  return trimmed.startsWith('#') || trimmed.startsWith(';')
}

/** Normalise a parameter name: case- and space-insensitive (Samba semantics). */
export function normalizeKey(name: string): string {
  return name.toLowerCase().replace(KEY_WS_RE, '')
}

/**
 * One LOGICAL line as Samba's reader sees it: a comment is one physical line
 * (a trailing backslash does not continue it), while a header or a parameter
 * line runs on through every physical line whose last non-blank character is
 * a backslash — the backslash dropped, the next line appended — so a line
 * after `path = /x \` is part of the value even when it reads `[next]` or
 * `# not a comment`. A backslash followed only by blanks before the newline
 * IS at the line end: `comment = Storage \ ` + `path = /srv/a` is ONE
 * parameter to Samba (testparm 4.22.11 on a PVE 9 node, cr4.conf D-4; the
 * same rule the write gate applies in shared/formats/smb-conf.ts).
 */
interface LogicalLine {
  kind: 'comment' | 'header' | 'param'
  /** First and last physical line indexes. */
  first: number
  last: number
  /** The joined content, whitespace runs collapsed and trimmed (Samba's view). */
  text: string
}

/** The logical lines of `lines[from, to)`; blank lines produce none. */
function logicalLines(lines: string[], from: number, to: number): LogicalLine[] {
  const out: LogicalLine[] = []
  let i = from
  while (i < to) {
    const lead = content(lines[i]).replace(LEADING_WS_RE, '')
    if (lead === '') {
      i++
      continue
    }
    if (isComment(lead)) {
      out.push({ kind: 'comment', first: i, last: i, text: trimSamba(lead) })
      i++
      continue
    }
    let joined = content(lines[i])
    let last = i
    while (last + 1 < to && trimEndSamba(joined).endsWith('\\')) {
      joined = trimEndSamba(joined).slice(0, -1) + content(lines[last + 1])
      last++
    }
    const text = trimSamba(collapseSamba(joined))
    out.push({ kind: text.startsWith('[') ? 'header' : 'param', first: i, last, text })
    i = last + 1
  }
  return out
}

/**
 * A header's section name the way Samba reads it: the text after `[` up to
 * the FIRST `]`, anything after it ignored (`[private] ; staff only` is
 * `private`, `[odd]x` is `odd`, `[a]b]` is `a`). Null when there is no `]` or
 * the name is empty — Samba refuses to load such a file at all.
 */
function headerName(text: string): { name: string, raw: string } | null {
  const close = text.indexOf(']')
  if (close === -1)
    return null
  // `raw` keeps the brackets' inner blanks: Samba stores `[ public]` as
  // " public", a different service from `[public]` (testparm 4.25).
  const raw = text.slice(1, close)
  const name = trimSamba(raw)
  return name === '' ? null : { name, raw }
}

/**
 * Split a parameter's logical text into its parts, or null if it is not one.
 * Keys are normalised (lower-cased, spaces removed) so "Read Only" === "readonly".
 */
function parseKeyLine(text: string): { key: string, value: string } | null {
  const eq = text.indexOf('=')
  if (eq === -1)
    return null
  const rawKey = trimSamba(text.slice(0, eq))
  if (!rawKey)
    return null
  return { key: normalizeKey(rawKey), value: trimSamba(text.slice(eq + 1)) }
}

/**
 * Parse the file text into the round-trip document model. Never loses data:
 * `lines` is exactly `text.split('\n')`, so `join('\n')` reconstructs `text`.
 */
export function parseDoc(text: string): SmbConfDoc {
  const lines = text.split('\n')
  return { lines, sections: computeSections(lines) }
}

/**
 * Build the section overlay for a line array.
 *
 * Spans are INDEXES into `lines`, so they go stale the moment the array is
 * spliced. Any editor that adds or removes lines must recompute them (see
 * `reindexSections`) before using a span again — a stale `end` is how an insert
 * lands in the NEXT stanza (issue #36).
 */
function computeSections(lines: string[]): SectionSpan[] {
  const headers = logicalLines(lines, 0, lines.length).filter(l => l.kind === 'header')

  const sections: SectionSpan[] = []
  if (headers.length === 0) {
    // Whole file is a headerless preamble (comments / blanks / stray keys).
    // `''.split('\n')` is `['']` — an empty file has no section at all.
    if (lines.length > 1 || lines[0] !== '')
      sections.push({ name: null, key: null, headerIndex: null, start: 0, bodyStart: 0, end: lines.length })
    return sections
  }

  // Leading preamble before the first header.
  if (headers[0].first > 0)
    sections.push({ name: null, key: null, headerIndex: null, start: 0, bodyStart: 0, end: headers[0].first })

  for (let h = 0; h < headers.length; h++) {
    const start = headers[h].first
    const end = h + 1 < headers.length ? headers[h + 1].first : lines.length
    const header = headerName(headers[h].text)
    sections.push({
      name: header?.raw ?? null,
      key: header ? smbSectionKey(header.raw) : null,
      headerIndex: start,
      start,
      bodyStart: headers[h].last + 1,
      end,
    })
  }

  return sections
}

/** Recompute the section overlay after `doc.lines` has been spliced. */
function reindexSections(doc: SmbConfDoc): void {
  doc.sections = computeSections(doc.lines)
}

/** Reconstruct the file text from the document model (byte-for-byte on no-op). */
export function serializeDoc(doc: SmbConfDoc): string {
  return doc.lines.join('\n')
}

/**
 * Every stanza Samba reads as ONE service: the sections whose names are equal
 * once whitespace runs are collapsed and case folded (`[public]` twice is one
 * share; `[pub lic]` and `[PUB  LIC]` too). Every `[global]` spelling, and the
 * preamble, is the global service (testparm 4.25).
 */
export interface SectionGroup {
  /** Name of the first section, as Samba holds it. */
  name: string
  key: string
  /** The sections Samba merges, in file order (never empty). */
  spans: SectionSpan[]
}

/**
 * Every service of the file in order of first appearance (unloadable headers
 * skipped). cr3.shares (review): parameters BEFORE the first section header
 * are Samba's `[global]` parameters (testparm 4.25: a file starting
 * `workgroup = PRE` serves it as the workgroup; a BOM before `[global]`
 * hides the header and its lines land here the same way), so the preamble is
 * the global service's FIRST section: read with it, and edited in place
 * when the file has no `[global]` header — never a second `[global]`.
 */
function sectionGroups(doc: SmbConfDoc): SectionGroup[] {
  const groups = new Map<string, SectionGroup>()
  for (const span of doc.sections) {
    if (span.headerIndex === null) {
      groups.set('global', { name: 'global', key: 'global', spans: [span] })
      continue
    }
    if (span.key === null || span.name === null)
      continue
    const group = groups.get(span.key)
    if (group)
      group.spans.push(span)
    else
      groups.set(span.key, { name: span.name, key: span.key, spans: [span] })
  }
  return [...groups.values()]
}

/** Find the service a name addresses (Samba's lookup), or null. */
function findGroup(doc: SmbConfDoc, name: string): SectionGroup | null {
  const key = smbSectionKey(name)
  return sectionGroups(doc).find(g => g.key === key) ?? null
}

/**
 * Every line index a service occupies (its merged sections), in file order —
 * the share guard hashes these for the stanza's revision.
 */
export function serviceLineRanges(text: string, name: string): { start: number, end: number }[] | null {
  const doc = parseDoc(text)
  const group = findGroup(doc, name)
  if (!group)
    return null
  return group.spans
    .map(s => ({ start: s.start, end: s.end }))
}

/** One `key = value` definition inside a section (continuation lines folded in). */
interface KeyDef {
  /** Normalised parameter name (case- and space-folded). */
  key: string
  /** Value as Samba reads it: continuations joined, whitespace runs collapsed, trimmed. */
  value: string
  /** Index of the `key =` line. */
  first: number
  /** Index of its last continuation line (=== `first` when there is none). */
  last: number
}

/**
 * Every parameter definition in a section, IN FILE ORDER, with continuation
 * lines folded into the value (and skipped by the scan, so a continuation that
 * happens to contain `=` is never mistaken for a parameter).
 *
 * This is the one place lines are interpreted: both the read-models and the
 * surgical editor work from it, so what ANAS shows and what ANAS edits can
 * never disagree.
 */
function sectionDefs(doc: SmbConfDoc, span: SectionSpan): KeyDef[] {
  const defs: KeyDef[] = []
  for (const l of logicalLines(doc.lines, span.bodyStart, span.end)) {
    if (l.kind !== 'param')
      continue
    const parsed = parseKeyLine(l.text)
    if (parsed)
      defs.push({ key: parsed.key, value: parsed.value, first: l.first, last: l.last })
  }
  return defs
}

/** Every definition of a service, across its merged sections, in file order. */
function groupDefs(doc: SmbConfDoc, group: SectionGroup): KeyDef[] {
  return group.spans.flatMap(span => sectionDefs(doc, span))
}

