/** {@link SAMBA_FOLD_RUNS} as a map: code point -> the code point it folds to. */
const SAMBA_FOLD: ReadonlyMap<number, number> = new Map(SAMBA_FOLD_RUNS.flatMap(([first, count, step, delta]) =>
  Array.from({ length: count }, (_, i): [number, number] => [first + i * step, first + i * step + delta])))

/**
 * How Samba tells services apart (testparm 4.25, cr3.shares review): by the
 * name with each whitespace run collapsed, case folded, whitespace KEPT —
 * `[pub lic]`, `[public]` and `[ public]` are three shares, all served, and
 * `[PUB  LIC]` merges into `[pub lic]`. Only the global section is found
 * whitespace-blind (`[ Glo bal ]` IS `[global]`).
 *
 * The fold is Samba's table ({@link SAMBA_FOLD}), never the engine's case
 * mapping: a character Samba merges with another becomes its class's lowest
 * code point, every other character is kept. So `k` and the Kelvin sign, `s`
 * and the long s, the micro sign and Greek mu, final sigma, dotless i, the
 * `ǅ` digraph, `ș`/`Ș` and every pair Samba's older table does not know stay
 * apart, as testparm serves them, while `Media`/`MEDIA` and `ÿy`/`ŸY` merge.
 * The key is compared, never shown.
 */
export function smbSectionKey(name: string): string {
  const folded = Array.from(collapseSamba(name), (ch) => {
    const to = SAMBA_FOLD.get(ch.codePointAt(0) ?? 0)
    return to === undefined ? ch : String.fromCodePoint(to)
  }).join('')
  return folded.replace(KEY_WS_RE, '') === 'GLOBAL' ? 'global' : folded
}

