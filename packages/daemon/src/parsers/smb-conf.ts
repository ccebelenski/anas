/**
 * Samba's whitespace is C `isspace()` in the C locale — the six ASCII blanks,
 * never U+00A0 or U+FEFF (testparm 4.25, cr3.shares H1: a line starting with
 * a no-break space is not a section header, a UTF-8 BOM before `[global]`
 * hides that header). Every trim and fold below uses this set, never `\s`.
 */
const SAMBA_WS = ' \t\n\v\f\r'
const LEADING_WS_RE = /^[\t\n\v\f\r ]*/
const TRAILING_WS_RE = /[\t\n\v\f\r ]*$/
/** Runs of whitespace, for folding parameter and section names. */
const KEY_WS_RE = /[\t\n\v\f\r ]+/g
/**
 * Samba's list separators (`LIST_SEP`: space, tab, comma, semicolon, CR, LF —
 * testparm reads `valid users = alice;bob` as two entries).
 */
const LIST_SEP_RE = /[\t\n\r ,;]+/

/** Is `c` one of Samba's whitespace characters? */
function isSambaSpace(c: string): boolean {
  return c.length === 1 && SAMBA_WS.includes(c)
}

/** Trim Samba's whitespace (ASCII only) from both ends. */
function trimSamba(s: string): string {
  return s.replace(LEADING_WS_RE, '').replace(TRAILING_WS_RE, '')
}

/** Trim Samba's whitespace (ASCII only) from the end. */
function trimEndSamba(s: string): string {
  return s.replace(TRAILING_WS_RE, '')
}

/**
 * Samba's line reader keeps a whitespace character only when the character
 * before it is not whitespace: `path = /srv/My  Data` serves `/srv/My Data`,
 * `[x   y]` is the section `x y` (testparm 4.25, cr3.shares H1).
 */
function collapseSamba(s: string): string {
  let out = ''
  for (const c of s) {
    if (isSambaSpace(c) && out.length > 0 && isSambaSpace(out.at(-1) ?? ''))
      continue
    out += c
  }
  return out
}

